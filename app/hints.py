"""等 AI 回答时先让用户开口的垫话。

每句控制在 10~15 字，正常语速念出来约 2~3 秒，
刚好覆盖「ASR 识别 + 模型首字」这段等待时间。
"""

from __future__ import annotations

import random

HINTS = [
    "嗯，这个问题我稍微想一下哈。",
    "好的，我先把思路理一下。",
    "嗯，这个我想几秒钟再答。",
    "这个问题我组织一下语言。",
    "嗯，我分两点说一下吧。",
    "好的，我回忆一下具体细节。",
    "嗯，这个当时确实踩过坑。",
    "我想想怎么讲比较清楚。",
    "嗯，我从实际用过的角度说。",
    "好的，我先说个大概结论。",
    "这个问题挺典型的，我想想。",
    "嗯，我梳理一下就回答你。",
    "让我先把核心点想清楚。",
    "嗯，这个得分情况来看。",
    "好的，我简单理一下就答。",
    "嗯，这块我印象还挺深的。",
    "我先想一下最关键的哪点。",
    "嗯，我觉得可以从这儿说。",
    "好的，我稍微停顿一下哈。",
    "嗯，我确认一下再跟你说。",
]

_last = ""


def pick_hint() -> str:
    """随机取一句垫话，避免连续两次相同。"""
    global _last
    choices = [item for item in HINTS if item != _last] or HINTS
    _last = random.choice(choices)
    return _last
